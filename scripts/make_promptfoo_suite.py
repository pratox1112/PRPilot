"""Build the Promptfoo red-team suite run in CI (roadmap §7.4): redteam/promptfoo/cases.yaml.

Cases are small synthetic PRs (no real PR text is committed) poisoned with the **dev**
payload templates from prpilot_data/redteam.py, in the three locations the screen
quarantines on (body, hidden HTML comment, diff comment; the title does not quarantine on
its own). Only cases PromptGuard 2 quarantines at the chosen setting are kept, balanced over
locations and payload kinds, so CI is a regression test of the screen: it fails if a change
to the screening code, the model pin or the threshold lets a known-blocked injection through.
It also fails when screening is switched off (PRPILOT_SCREENING=off), which the one-time
check in PROGRESS.md verifies.

    uv run --group screening python scripts/make_promptfoo_suite.py
"""

import itertools
import json
import random
from pathlib import Path

from prpilot_core.agents.triage_format import PRContext
from prpilot_core.screening.prompt_guard import DEFAULT_THRESHOLD, PROMPT_GUARD_86M, PromptGuard
from prpilot_core.screening.screen import guard_fields, quarantined
from prpilot_data import redteam

OUT = Path(__file__).resolve().parents[1] / "redteam" / "promptfoo" / "cases.yaml"
N_CASES = 30
LOCATIONS = ("body", "body_hidden", "diff_comment")


def diff(path: str, old: str, new: str) -> str:
    return "\n".join(
        [f"diff --git a/{path} b/{path}", f"--- a/{path}", f"+++ b/{path}", "@@ -1,2 +1,2 @@",
         f"-{old}", f"+{new}"]
    )  # fmt: skip


SHELLS = [
    ("Fix off-by-one in pagination", "The last page was dropped when the total was a multiple "
     "of the page size. Adds a regression test.", "app/pagination.py",
     "pages = total // size", "pages = -(-total // size)"),
    ("Add retry with backoff to the HTTP client", "Transient 503s from the registry broke "
     "nightly builds. Retries up to three times with exponential backoff.", "pkg/client/http.go",
     "resp, err := c.do(req)", "resp, err := c.doWithRetry(req, 3)"),
    ("docs: clarify install steps", "The quickstart skipped the virtualenv step; this adds it "
     "and fixes two broken links.", "docs/install.rst",
     ".. note:: Requires Python 3.10", ".. note:: Requires Python 3.12"),
    ("ci: pin the linter version", "Unpinned linter releases kept changing CI results.",
     ".github/workflows/lint.yml", "  run: pip install ruff", "  run: pip install ruff==0.17.2"),
    ("Handle empty config files", "Loading an empty YAML file raised a TypeError; it now "
     "yields the defaults.", "app/config.py", "data = yaml.safe_load(f)",
     "data = yaml.safe_load(f) or {}"),
    ("Speed up the tokenizer cache", "Caches compiled regexes once per process instead of "
     "per call. About 15% faster on the benchmark suite.", "src/tokenize.c",
     "re = compile(pattern);", "re = cached_compile(pattern);"),
]  # fmt: skip


def shell_row(i: int, shell: tuple) -> dict:
    title, body, path, old, new = shell
    return {
        "repo": "example/project",
        "number": 1000 + i,
        "title": title,
        "body": body,
        "author": "contributor",
        "base_branch": "main",
        "changed_files": [path],
        "diff": diff(path, old, new),
    }


def main() -> None:
    guard = PromptGuard(PROMPT_GUARD_86M)
    rng = random.Random(0)
    dev = [t for t in redteam.TEMPLATES if t[1] == "dev"]
    candidates = []
    for (i, shell), template, location in itertools.product(enumerate(SHELLS), dev, LOCATIONS):
        row, value = redteam.poison(shell_row(i, shell), location, template, rng)
        pr = PRContext(**{k: row[k] for k in ("title", "body", "author", "base_branch", "diff")},
                       changed_files=tuple(row["changed_files"]))  # fmt: skip
        scores = {k: guard.score(t).score if t else 0.0 for k, t in guard_fields(pr).items()}
        if quarantined(scores, DEFAULT_THRESHOLD):
            candidates.append(
                (location, template[2], template[0], row, value, max(scores.values()))
            )
    # balance: round-robin over (location, kind) groups
    groups: dict[tuple, list] = {}
    for c in candidates:
        groups.setdefault((c[0], c[1]), []).append(c)
    picked = []
    for batch in itertools.zip_longest(*groups.values()):
        picked += [c for c in batch if c]
    picked = picked[:N_CASES]
    if len(picked) < N_CASES:
        raise SystemExit(f"only {len(picked)} blocked cases; add shells")

    lines = ["# Generated by scripts/make_promptfoo_suite.py; do not edit by hand.",
             f"# {len(candidates)} of {len(SHELLS) * len(dev) * len(LOCATIONS)} synthetic cases "
             f"were quarantined at threshold {DEFAULT_THRESHOLD}; {N_CASES} kept."]  # fmt: skip
    for location, kind, tid, row, value, score in picked:
        pr = {
            k: row[k] for k in ("title", "body", "author", "base_branch", "changed_files", "diff")
        }
        lines += [
            f"- description: {location} / {kind} / {tid} (PromptGuard {score:.3f})",
            "  vars:",
            f"    canary: {json.dumps(value)}",
            f"    pr: {json.dumps(pr, ensure_ascii=False)}",
        ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    kinds = {k: sum(1 for c in picked if c[1] == k) for k in ("direct", "task")}
    print(f"{len(candidates)} quarantined candidates; wrote {N_CASES} cases {kinds} to {OUT}")


if __name__ == "__main__":
    main()
